# -*- coding: utf-8 -*-
"""Якутское написание -> «русская» запись для синтезатора.

Русский TTS не знает якутских букв, поэтому ө/ү/ҕ/һ/ҥ он читает на русский
манер (күн -> «кун», үөрэтэбин -> «уэрэтэбин», саҥарабыз -> «сагарабыз»).
Подменяем буквы на ближайшие русские так, чтобы синтезатор выдал похожий звук:
  ө -> ё   (ё после согласного даёт о с продвинутым вперёд языком)
  ү -> ю   (ю после согласного даёт у с продвинутым вперёд языком)
  ҕ -> г   (ближайший к якутскому щелевому «г»)
  һ -> х   (якутский «һ» = выдох, ближе всего к х)
  ҥ -> нг  (заднеязычный носовой)
  дь, нь остаются как есть — в русском они и так мягкие.

Лучше русского звучат тюркские голоса: в турецком и азербайджанском есть
ровно те звуки, которых нет в русском — ö [ø], ü [y], ı [ɯ], ğ [ɣ], h, ng.
Для них якутский текст переписывается латиницей (respell_for(text, 'tr'|'az')),
а для казахского достаточно ҕ -> ғ и ҥ -> ң ('kk').
"""
import re

# названия букв так, как их произносят по-якутски
LETTER_NAME = {
    'а': 'а', 'э': 'э', 'и': 'и', 'о': 'о', 'ө': 'ё', 'у': 'у', 'ү': 'ю', 'ы': 'ы',
    'аа': 'аа', 'ээ': 'ээ', 'ии': 'ии', 'оо': 'оо', 'өө': 'ёё', 'уу': 'уу', 'үү': 'юю', 'ыы': 'ыы',
    'ыа': 'ыа', 'иэ': 'иэ', 'уо': 'уо', 'үө': 'юё',
    'б': 'бэ', 'в': 'вэ', 'г': 'гэ', 'ҕ': 'га', 'д': 'дэ', 'дь': 'дьэ', 'ж': 'жэ', 'з': 'зэ',
    'й': 'й', 'к': 'ка', 'л': 'лэ', 'м': 'мэ', 'н': 'нэ', 'ҥ': 'нга', 'нь': 'ньэ',
    'п': 'пэ', 'р': 'рэ', 'с': 'сэ', 'һ': 'ха', 'т': 'тэ', 'ф': 'фэ', 'х': 'хэ',
    'ц': 'цэ', 'ч': 'чэ', 'ш': 'шэ', 'щ': 'щэ', 'ъ': '', 'ь': '',
}

MAP = [
    ('дь', 'дь'), ('нь', 'нь'),
    ('ҕ', 'г'), ('ҥ', 'нг'), ('һ', 'х'),
]

CONS = set('бвгҕджзйклмнҥньпрсһтфхцчшщБВГҔДЖЗЙКЛМНҤНЬПРСҺТФХЦЧШЩ')


def _soft_pairs(t: str) -> str:
    """ө/ү после согласной -> ё/ю (мягкость), в начале слова и после гласной -> о/у."""
    out = []
    for i, ch in enumerate(t):
        prev = t[i - 1] if i else ''
        if ch in 'өӨ':
            out.append(('ё' if ch == 'ө' else 'Ё') if prev in CONS else ('о' if ch == 'ө' else 'О'))
        elif ch in 'үҮ':
            out.append(('ю' if ch == 'ү' else 'Ю') if prev in CONS else ('у' if ch == 'ү' else 'У'))
        else:
            out.append(ch)
    return ''.join(out)


LAT = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ж': 'j', 'з': 'z',
    'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p',
    'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'ц': 'ts', 'ч': 'ç', 'ш': 'ş',
    'щ': 'şç', 'ъ': '', 'ы': 'ı', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya', 'ё': 'yo',
    'ө': 'ö', 'ү': 'ü', 'һ': 'h', 'ҕ': 'ğ', 'ҥ': 'ng',
}
LAT_X = dict(LAT, х='h')      # турецкий: х -> h
LAT_AZ = dict(LAT, х='x')     # азербайджанский: х -> x
LAT_DIGRAPH = [('дь', 'c'), ('нь', 'ny')]
KK = {'ҕ': 'ғ', 'ҥ': 'ң'}


def _to_latin(t: str, table: dict) -> str:
    for a, b in LAT_DIGRAPH:
        t = t.replace(a, b).replace(a.upper(), b.capitalize())
    out = []
    for ch in t:
        rep = table.get(ch.lower())
        if rep is None:
            out.append(ch)
        else:
            out.append(rep if ch.islower() else (rep[:1].upper() + rep[1:]))
    return ''.join(out)


def respell_for(s: str, lang: str = 'ru') -> str:
    """Фонетическая запись под конкретный язык синтезатора."""
    t = re.sub(r'[!?.;:"]', '', s.strip())
    t = re.sub(r'\s+', ' ', t).strip()
    if lang == 'tr':
        return _to_latin(t, LAT_X)
    if lang == 'az':
        return _to_latin(t, LAT_AZ)
    if lang == 'kk':
        return ''.join(KK.get(ch, ch) for ch in t)
    return respell(t)


def respell(s: str) -> str:
    """Фраза или слово: подменяем «неудобные» буквы, сохраняя регистр первого символа."""
    low = _soft_pairs(s.strip())
    for a, b in MAP:
        low = low.replace(a, b).replace(a.upper(), b)
    # убираем знаки, которые мешают ровному чтению
    low = re.sub(r'[!?.;:"]', '', low)
    low = re.sub(r'\s+', ' ', low).strip()
    return low


def say(text: str) -> str:
    """Что именно подать синтезатору для конкретной строки приложения."""
    t = text.strip()
    key = t.lower()
    if key in LETTER_NAME:
        # названия букв уже в «русской» записи
        return LETTER_NAME[key]
    # одиночная буква в верхнем регистре
    if len(key) == 1 and key in LETTER_NAME:
        return LETTER_NAME[key]
    return respell(t)


if __name__ == '__main__':
    import json, sys
    items = json.load(open(sys.argv[1], encoding='utf-8')) if len(sys.argv) > 1 else None
    if items:
        for k in ('words', 'sentences', 'letters'):
            for w in items[k]:
                print(f'{w!r:32} -> {say(w)!r}')
